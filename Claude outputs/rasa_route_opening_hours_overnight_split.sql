-- ---------------------------------------------------------------------------
-- THE SCHEMA, AS INSPECTED
-- ---------------------------------------------------------------------------
--   opening_hours_id  bigint  GENERATED BY DEFAULT AS IDENTITY, primary key
--   day               public.day enum: Monday .. Sunday
--   opening_time      time, nullable
--   closing_time      time, nullable
--   landmark_id       bigint -> submitted_landmark, nullable
--   restaurant_id     bigint -> restaurant, nullable
--   status            public.status_enum: open | closed | unknown
--
--   unique (restaurant_id, day, opening_time, closing_time) NULLS NOT DISTINCT
--          WHERE restaurant_id is not null          <- no landmark equivalent
--   no triggers
--
-- ---------------------------------------------------------------------------
-- THE TWO PROBLEMS
-- ---------------------------------------------------------------------------
-- 1. The identity sequence was BEHIND the table. `GENERATED BY DEFAULT`
--    means an explicit-id insert does not advance the sequence, so a bulk load
--    that supplied ids left it at 303,716 against a max id of 303,722. The
--    next six inserts that let the identity generate would have collided with
--    rows that already existed - the reported
--        duplicate key value violates unique constraint "opening_hours_pkey"
--
-- 2. An overnight slot was one row whose closing time is EARLIER than its
--    opening time - `Monday 22:00-02:00` - so every reader had to know to wrap
--    it round midnight. Split into two rows it is ordinary data.
--
-- ---------------------------------------------------------------------------
-- WHAT IT FOUND, AND DID
-- ---------------------------------------------------------------------------
--   116,322 rows before, 124,383 after - exactly +8,061, nothing deleted
--    15,221 overnight rows, every one of them a restaurant
--     7,160 closed exactly at midnight -> closing time becomes 24:00 and NO
--           second row is written, because `00:00-00:00` is not a slot
--     8,061 needed a second row; none collided with a slot already present,
--           and all 8,061 were distinct from each other
--         9 rows already ended at 24:00 - left alone
--         2 rows have opening = closing, which is not `<` - left alone
--     8,039 rows have a null time - left alone
--         0 overnight rows remain
--
--   Worked example, restaurant "Pasembur King (Hussain)":
--       before   Sunday 11:30-00:30   Monday 11:45-00:15
--       after    Sunday 11:30-24:00   Monday 00:00-00:30
--                Monday 11:45-24:00   Tuesday 00:00-00:15
--   Both of Monday's slots survive, which is the point of doing this per row.
-- ===========================================================================


-- ---------------------------------------------------------------------------
-- 1. The sequence
-- ---------------------------------------------------------------------------
-- `pg_get_serial_sequence` rather than the sequence's literal name, so this
-- stays correct if the sequence is ever renamed. `true` for is_called means
-- the next value handed out is max + 1.
select setval(
  pg_get_serial_sequence('public.opening_hours', 'opening_hours_id'),
  (select coalesce(max(opening_hours_id), 0) from public.opening_hours),
  true
);


-- ---------------------------------------------------------------------------
-- 2. The second half of every overnight slot
-- ---------------------------------------------------------------------------
-- The next day is read off the enum itself - `array_position` into
-- `enum_range`, wrapped with a modulo - rather than a seven-branch CASE over
-- hard-coded labels. Sunday wraps to Monday, and nothing breaks if a label is
-- renamed or the enum is reordered.
--
-- Three independent guards make this safe to run again:
--   * `distinct` collapses two overnight slots that would produce the same
--     tail row;
--   * `not exists` skips a tail already in the table;
--   * `on conflict do nothing` is the backstop for the restaurant unique
--     index (and the only protection landmarks would get, since they have no
--     equivalent index - see the note at the end).
-- A second run is a no-op for a fourth reason as well: after step 3 no row
-- satisfies `closing_time < opening_time` any more. Verified: a second pass
-- inserts 0 rows and updates 0 rows.
--
-- The id is left to the identity, which step 1 has just made safe.
with overnight as (
  select distinct
         (enum_range(null::public.day))[
           (array_position(enum_range(null::public.day), oh.day)
             % array_length(enum_range(null::public.day), 1)) + 1 ] as tail_day,
         oh.closing_time,
         oh.restaurant_id,
         oh.landmark_id,
         oh.status
    from public.opening_hours oh
   where oh.opening_time is not null
     and oh.closing_time is not null
     and oh.closing_time < oh.opening_time
     -- A slot that closes at midnight has no next-day half.
     and oh.closing_time > time '00:00:00'
)
insert into public.opening_hours (
  day, opening_time, closing_time, restaurant_id, landmark_id, status
)
select o.tail_day, time '00:00:00', o.closing_time,
       o.restaurant_id, o.landmark_id, o.status
  from overnight o
 where not exists (
   select 1
     from public.opening_hours e
    where e.day = o.tail_day
      and e.opening_time = time '00:00:00'
      and e.closing_time = o.closing_time
      -- `is not distinct from`, so the null side of the pair matches too: a
      -- landmark row has a null restaurant_id, and `=` against null is never
      -- true, which would make this guard silently useless for landmarks.
      and e.restaurant_id is not distinct from o.restaurant_id
      and e.landmark_id  is not distinct from o.landmark_id
 )
on conflict do nothing;


-- ---------------------------------------------------------------------------
-- 3. The first half now ends at the end of the day
-- ---------------------------------------------------------------------------
-- Postgres `time` accepts 24:00:00, which is exactly what is meant: this slot
-- runs to the end of this day and the row inserted above carries the rest.
--
-- The rows inserted in step 2 open at 00:00 and close later, so they do not
-- satisfy this predicate and are not touched by it. Order matters the other
-- way round, though: the insert has to read the overnight rows BEFORE this
-- update rewrites them, or the tail times are gone.
update public.opening_hours
   set closing_time = time '24:00:00'
 where opening_time is not null
   and closing_time is not null
   and closing_time < opening_time;


