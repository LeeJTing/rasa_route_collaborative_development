-- 1. LANDMARKS HAVE NO UNIQUE INDEX. Restaurants are protected by
--    `opening_hours_restaurant_schedule_uniq`; the landmark side has nothing,
--    so duplicate landmark slots can be inserted by any path, not just this
--    one. There are 40 landmark rows and none of them is overnight, so this
--    migration was never at risk - but the gap is real. The fix, once the
--    existing rows are confirmed duplicate-free:
--
--      create unique index concurrently if not exists
--        opening_hours_landmark_schedule_uniq
--        on public.opening_hours (landmark_id, day, opening_time, closing_time)
--        nulls not distinct
--        where landmark_id is not null;
--
--    `concurrently` cannot run inside a transaction, which is why it is not
--    part of the migration above.
--
-- 2. READERS NOW SEE 24:00. Anything that formats these rows will print
--    "24:00" where it used to print "00:00", and anything that still contains
--    wrap-around logic for `closing < opening` now has dead code in it. The
--    unapplied `hours_overlap_meal` / `open_for_meal` functions in
--    `rasa_route_migrations_2026-09-11.sql` expand wrapping intervals by hand;
--    that half of them is now unnecessary, though harmless.


-- ===========================================================================
-- ADDENDUM, same day: compact the primary key to 1 .. count(*)
-- ===========================================================================
-- Applied as `opening_hours_compact_ids_from_one`.
--
-- After the split the table held 124,383 rows numbered 16 .. 311,783 - 187,400
-- numbers of gap, left by bulk loads and by a client that supplied its own ids.
--
-- SAFE because **nothing references `opening_hours_id`**: `pg_constraint` has
-- no foreign key whose `confrelid` is this table. The app reads the id (it
-- becomes `OpeningHour.id`, and it is the `orderBy` key that makes
-- `selectEvery` paging deterministic) but never stores it anywhere else, so a
-- renumber is invisible once rows are refetched.
--
-- WHY TWO PASSES: `opening_hours_pkey` is NOT deferrable, so uniqueness is
-- checked row by row as the update runs. Assigning 1..n directly collides the
-- moment a new id lands on an old one not yet rewritten - row 20 becoming 5
-- while the real 5 is still there. So shift clear of the range first, then come
-- back down.

-- Pass 1: lift every id above the old maximum, so no new value can hit an
-- existing one. The offset is read from the table, not typed.
update public.opening_hours
   set opening_hours_id = opening_hours_id
     + (select coalesce(max(opening_hours_id), 0) from public.opening_hours);

-- Pass 2: back down as 1 .. count(*). Every new value is far below the shifted
-- block, so again nothing collides. Ordering by the (uniformly shifted) id
-- preserves the original relative order exactly.
with renumbered as (
  select opening_hours_id as old_id,
         row_number() over (order by opening_hours_id) as new_id
    from public.opening_hours
)
update public.opening_hours oh
   set opening_hours_id = r.new_id
  from renumbered r
 where oh.opening_hours_id = r.old_id;

-- The sequence follows the data: next generated id is count + 1.
select setval(
  pg_get_serial_sequence('public.opening_hours', 'opening_hours_id'),
  (select coalesce(max(opening_hours_id), 0) from public.opening_hours),
  true
);

